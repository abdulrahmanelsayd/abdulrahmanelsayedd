import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, mkdir, writeFile, symlink, unlink, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { guardedNext } from "../../tools/next-guard.mjs";

test("portable guard preserves physical redirect and completed protected-output coverage", async t => {
  const fixtures = await mkdtemp(path.join(tmpdir(), "release-guard-"));
  t.after(() => rm(fixtures, { recursive: true, force: true }));
  const project = path.join(fixtures, "fresh"), saved = path.join(fixtures, "saved");
  await mkdir(project); await mkdir(saved); await mkdir(path.join(project, "src"));
  await writeFile(path.join(project, "next.config.ts"), "export default {};");
  await writeFile(path.join(saved, "BUILD_ID"), "preserved-build");
  await writeFile(path.join(fixtures, ".next-guard.local.json"), JSON.stringify({version:1, protectProject:true, protectedPaths:["saved"]}));
  let invocations = 0;
  const run = async () => { invocations++; return 0; };
  const config = async () => ({distDir:".next"});
  const options = {root:project, cwd:project, args:["build"]};
  const reject = async (overrides: Partial<typeof options> = {}, load = config) => {
    const count = invocations;
    await assert.rejects(guardedNext({...options, ...overrides}, run, load), /BUILD GUARD/);
    assert.equal(invocations, count, "rejected before Next is invoked");
  };
  await reject({cwd:fixtures});
  await reject({args:["build", saved]});
  await reject({args:["typegen", "--directory", saved]});
  await reject({args:["build", project, project]});
  await reject({args:["dev"]});
  const alias = path.join(fixtures, "alias");
  await symlink(saved, alias, "junction");
  await reject({root:alias,cwd:alias});
  await symlink(saved, path.join(project, ".next"), "junction");
  await reject(); await unlink(path.join(project, ".next"));
  await mkdir(path.join(project, ".next"));
  await symlink(saved, path.join(project, ".next/types"), "junction");
  await reject(); await unlink(path.join(project, ".next/types"));
  await symlink(saved, path.join(project, "src/nested"), "junction");
  await reject(); await unlink(path.join(project, "src/nested"));
  await reject({}, async () => ({distDir:saved}));
  await reject({}, async () => ({distDir:".next",typescript:{tsconfigPath:"other.json"}}));
  await reject({}, async () => ({distDir:".next",output:"export"}));
  await writeFile(path.join(project, "next.config.mjs"), "export default {};");
  await reject(); await unlink(path.join(project, "next.config.mjs"));
  await reject({root:saved,cwd:saved});
  assert.equal(invocations, 0);
  assert.equal(await guardedNext(options, run, config), 0);
  assert.equal(await guardedNext({...options,args:["typegen",project]}, run, config), 0);
  assert.equal(invocations, 2);
});
